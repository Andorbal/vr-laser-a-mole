def time(dur):
    return np.arange(int(dur * SR)) / SR


def phase_of(freq, n):
    """Phase (radians) of an oscillator whose frequency may vary per sample."""
    f = np.broadcast_to(np.asarray(freq, dtype=np.float64), (n,))
    return 2.0 * np.pi * np.cumsum(f) / SR


def sweep(f0, f1, n, curve=1.0):
    """Exponential-ish frequency sweep from f0 to f1 over n samples."""
    x = np.linspace(0.0, 1.0, n) ** curve
    return f0 * (f1 / f0) ** x


def additive(freq, n, kind="saw", cutoff=None, order=2.0, max_harm=80):
    """Band-limited oscillator built from harmonics, with an optional
    (time-varying) low-pass that rolls harmonics off smoothly."""
    f = np.broadcast_to(np.asarray(freq, dtype=np.float64), (n,))
    ph = phase_of(f, n)
    out = np.zeros(n)
    cut = None if cutoff is None else np.broadcast_to(np.asarray(cutoff, dtype=np.float64), (n,))
    for k in range(1, max_harm + 1):
        if kind == "square" and k % 2 == 0:
            continue
        if kind == "triangle" and k % 2 == 0:
            continue
        fk = f * k
        if np.min(fk) > SR * 0.45:
            break
        if kind == "triangle":
            amp = (1.0 / (k * k)) * (1 if (k // 2) % 2 == 0 else -1)
        else:
            amp = 1.0 / k
        g = np.where(fk < SR * 0.45, amp, 0.0)
        if cut is not None:
            g = g / np.sqrt(1.0 + (fk / cut) ** (2.0 * order))
        out += g * np.sin(k * ph)
    return out


def sine(freq, n):
    return np.sin(phase_of(freq, n))


def noise(n):
    return RNG.uniform(-1.0, 1.0, n)


def env_exp(n, decay, attack=0.002):
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-5), 0.0, 1.0)
    return a * np.exp(-t / decay)


def env_adsr(n, a=0.01, d=0.1, s=0.7, r=0.1):
    t = np.arange(n) / SR
    dur = n / SR
    e = np.ones(n) * s
    e = np.where(t < a, t / max(a, 1e-5), e)
    e = np.where((t >= a) & (t < a + d), 1.0 - (1.0 - s) * (t - a) / max(d, 1e-5), e)
    rel_start = max(dur - r, a + d)
    e = np.where(t >= rel_start, s * np.clip(1.0 - (t - rel_start) / max(r, 1e-5), 0.0, 1.0), e)
    return e


def spectral_filter(x, gain_fn):
    """Static filter applied in the frequency domain. gain_fn(freqs) -> gains."""
    n = len(x)
    size = 1 << int(np.ceil(np.log2(max(n, 2))))
    spec = np.fft.rfft(x, size)
    freqs = np.fft.rfftfreq(size, 1.0 / SR)
    return np.fft.irfft(spec * gain_fn(freqs), size)[:n]


def lowpass(x, cutoff, order=2.0):
    return spectral_filter(x, lambda f: 1.0 / np.sqrt(1.0 + (f / cutoff) ** (2.0 * order)))


def highpass(x, cutoff, order=2.0):
    return spectral_filter(x, lambda f: 1.0 / np.sqrt(1.0 + (cutoff / np.maximum(f, 1e-3)) ** (2.0 * order)))


def bandpass(x, center, q=2.0):
    def g(f):
        f = np.maximum(f, 1e-3)
        return 1.0 / np.sqrt(1.0 + (q * (f / center - center / f)) ** 2)
    return spectral_filter(x, g)


def swept_band_noise(n, centers, q=3.0, block=1024):
    """Noise through a band-pass whose center follows `centers` (per sample).
    Done with overlapping FFT blocks."""
    x = noise(n + block)
    out = np.zeros(n + block)
    hop = block // 2
    win = np.hanning(block)
    freqs = np.fft.rfftfreq(block, 1.0 / SR)
    centers = np.broadcast_to(np.asarray(centers, dtype=np.float64), (n,))
    for start in range(0, n, hop):
        c = centers[min(start + hop, n - 1)]
        seg = x[start:start + block] * win
        f = np.maximum(freqs, 1e-3)
        g = 1.0 / np.sqrt(1.0 + (q * (f / c - c / f)) ** 2)
        out[start:start + block] += np.fft.irfft(np.fft.rfft(seg) * g, block)
    return out[:n]


def delay(x, seconds, feedback=0.4, taps=6, mix=0.35):
    d = int(seconds * SR)
    out = np.copy(x)
    g = mix
    for i in range(1, taps + 1):
        shifted = np.zeros_like(x)
        if d * i < len(x):
            shifted[d * i:] = x[:len(x) - d * i]
        out += shifted * g
        g *= feedback
    return out


def reverb_ir(seconds=1.6, decay=0.45, seed=7):
    rng = np.random.default_rng(seed)
    n = int(seconds * SR)
    t = np.arange(n) / SR
    ir = rng.uniform(-1.0, 1.0, n) * np.exp(-t / decay)
    ir = lowpass(ir, 6000.0)
    ir[0] = 0.0
    return ir / np.sqrt(np.sum(ir ** 2))


def convolve(x, ir):
    n = len(x) + len(ir) - 1
    size = 1 << int(np.ceil(np.log2(n)))
    return np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(ir, size), size)[:n]


def reverb(x, wet=0.25, seconds=1.4, decay=0.4):
    tail = convolve(x, reverb_ir(seconds, decay))
    out = np.zeros(len(tail))
    out[:len(x)] += x
    return out + tail * wet


def fade_out(x, seconds=0.01):
    n = min(len(x), int(seconds * SR))
    if n > 0:
        x[-n:] *= np.linspace(1.0, 0.0, n)
    return x


def pad_to(x, n):
    if len(x) >= n:
        return x[:n]
    return np.concatenate([x, np.zeros(n - len(x))])


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[:len(p)] += p
    return out


def note(name):
    """'A4' -> Hz. Sharps as 'C#4'."""
    names = {"C": -9, "C#": -8, "D": -7, "D#": -6, "E": -5, "F": -4, "F#": -3, "G": -2, "G#": -1, "A": 0, "A#": 1, "B": 2}
    pitch, octave = name[:-1], int(name[-1])
    return 440.0 * 2.0 ** ((names[pitch] + 12 * (octave - 4)) / 12.0)


def trim_silence(x, threshold_db=-60.0):
    """Drops the near-silent end of a sound (long reverb tails)."""
    level = 10 ** (threshold_db / 20.0) * np.max(np.abs(x))
    loud = np.nonzero(np.abs(x) > level)[0]
    if len(loud) == 0:
        return x
    end = min(len(x), loud[-1] + int(0.01 * SR))
    return fade_out(x[:end].copy(), 0.03)


def normalize(x, peak_db=-1.0):
    peak = np.max(np.abs(x))
    if peak < 1e-9:
        return x
    return x / peak * (10 ** (peak_db / 20.0))


def soft_clip(x, drive=1.5):
    return np.tanh(x * drive) / np.tanh(drive)


