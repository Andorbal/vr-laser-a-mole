def kick(n):
    f = sweep(160.0, 42.0, n, 0.35)
    return sine(f, n) * env_exp(n, 0.16, 0.001) + lowpass(noise(n), 2000.0) * env_exp(n, 0.004) * 0.3


def snare(n):
    tone = sine(sweep(240.0, 170.0, n), n) * env_exp(n, 0.05)
    body = bandpass(noise(n), 1800.0, 0.7) * env_exp(n, 0.12, 0.001)
    return tone * 0.5 + body * 0.9


def hat(n, open_hat=False):
    return highpass(noise(n), 7000.0, 3.0) * env_exp(n, 0.09 if open_hat else 0.025, 0.0005)


def place(track, sig, t0):
    s0 = int(t0 * SR)
    if s0 >= len(track):
        return
    m = min(len(sig), len(track) - s0)
    track[s0:s0 + m] += sig[:m]


def render_song(bpm, bars, chords, energy, lead=None, seed=0):
    """Returns a seamless stereo loop (2, n)."""
    beat = 60.0 / bpm
    bar = beat * 4
    length = bars * bar
    n = int(length * SR)
    tail = int(2.0 * SR)
    total = n + tail
    rng = np.random.default_rng(seed)
    drums = np.zeros(total)
    bass = np.zeros(total)
    pad = np.zeros(total)
    arp = np.zeros(total)
    lead_tr = np.zeros(total)
    side = np.zeros(total)

    kick_s = kick(int(0.35 * SR))
    snare_s = snare(int(0.3 * SR))
    hat_s = hat(int(0.06 * SR))
    ohat_s = hat(int(0.2 * SR), True)

    for b in range(bars):
        t_bar = b * bar
        root, tones = chords[(b // 2) % len(chords)]
        for q in range(4):
            tq = t_bar + q * beat
            if energy > 0.3 or q in (0, 2):
                place(drums, kick_s * (1.0 if energy > 0.3 else 0.7), tq)
                env = np.zeros(int(beat * SR))
                env[:] = np.exp(-np.arange(len(env)) / SR / 0.13)
                place(side, env, tq)
            if q in (1, 3) and energy > 0.3:
                place(drums, snare_s * 0.55, tq)
            for e in range(2 if energy <= 0.6 else 4):
                th = tq + e * beat / (2 if energy <= 0.6 else 4)
                accent = 1.0 if e % 2 == 1 else 0.6
                place(drums, (ohat_s if (e == 2 and q == 3 and energy > 0.6) else hat_s) * 0.18 * accent, th)

        # Bass: driving eighths on the root.
        for e in range(8):
            te = t_bar + e * beat / 2
            ln = int(beat / 2 * SR * 0.92)
            f = note(root) * (2.0 if (e % 4 == 3 and energy > 0.6) else 1.0)
            cut = 400.0 + 1600.0 * energy * np.exp(-np.arange(ln) / SR / 0.08)
            v = additive(f, ln, "saw", cutoff=cut, order=2.0, max_harm=50)
            v += additive(f * 0.5, ln, "square", cutoff=300.0, max_harm=10) * 0.5
            place(bass, v * env_adsr(ln, 0.004, 0.05, 0.8, 0.03) * 0.33, te)

        # Pad: detuned saws, slow swell, once per two bars.
        if b % 2 == 0:
            ln = int(bar * 2 * SR)
            v = np.zeros(ln)
            for nm in tones:
                for det in (0.993, 1.0, 1.007):
                    v += additive(note(nm) * det, ln, "saw", cutoff=1300.0 + 900.0 * energy, max_harm=40)
            place(pad, v * env_adsr(ln, 0.35, 0.5, 0.75, 0.6) * 0.045, t_bar)

        # Arpeggio: sixteenths through the chord tones.
        if energy > 0.15:
            seq = tones + [tones[1]]
            steps = 16 if energy > 0.5 else 8
            for s in range(steps):
                ts = t_bar + s * bar / steps
                ln = int(bar / steps * SR * 0.8)
                nm = seq[s % len(seq)]
                f = note(nm) * (2.0 if (s // 4) % 2 == 1 else 1.0)
                cut = 1500.0 + 2500.0 * (0.5 + 0.5 * np.sin(2 * np.pi * (b * steps + s) / 64.0))
                v = additive(f, ln, "square", cutoff=cut, max_harm=30) * env_exp(ln, 0.09, 0.002)
                place(arp, v * 0.07, ts)

    if lead:
        for (t_beats, nm, dur_beats) in lead:
            for rep in range(bars // 8):
                ts = rep * 8 * bar + t_beats * beat
                ln = int(dur_beats * beat * SR)
                tt = np.arange(ln) / SR
                vib = 1.0 + 0.006 * np.sin(2 * np.pi * 5.5 * tt) * np.clip(tt / 0.25, 0.0, 1.0)
                f = note(nm) * vib
                v = additive(f, ln, "saw", cutoff=3500.0, max_harm=40) + additive(f * 1.004, ln, "saw", cutoff=3500.0, max_harm=40)
                place(lead_tr, v * env_adsr(ln, 0.02, 0.1, 0.7, 0.12) * 0.07, ts)

    duck = 1.0 - 0.55 * np.clip(side, 0.0, 1.0)
    bass *= duck
    pad *= 1.0 - 0.35 * np.clip(side, 0.0, 1.0)

    arp_l = delay(arp, beat * 0.75, 0.45, 5, 0.4)
    arp_r = delay(arp, beat * 0.5, 0.45, 5, 0.4)
    lead_l = delay(lead_tr, beat * 0.75, 0.35, 4, 0.3)
    lead_r = delay(lead_tr, beat * 0.5, 0.35, 4, 0.3)
    pad_l = pad
    pad_r = np.concatenate([np.zeros(int(0.012 * SR)), pad[:-int(0.012 * SR)]])

    left = drums + bass + pad_l + arp_l * 0.8 + arp_r * 0.2 + lead_l
    right = drums + bass + pad_r + arp_r * 0.8 + arp_l * 0.2 + lead_r
    wet_src = (pad + arp + lead_tr + drums * 0.15)
    rev = convolve(wet_src, reverb_ir(2.2, 0.6, seed + 3))[:total] * 0.22
    left = left + rev
    right = right + np.concatenate([np.zeros(int(0.008 * SR)), rev[:-int(0.008 * SR)]])

    # Fold the tail back onto the start so the loop is seamless.
    out = np.stack([left, right])
    loop = out[:, :n].copy()
    loop[:, :tail] += out[:, n:n + tail]
    loop = soft_clip(loop * 0.9, 1.1)
    peak = np.max(np.abs(loop))
    return loop / peak * 0.89


