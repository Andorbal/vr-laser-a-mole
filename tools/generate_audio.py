def sfx_shot():
    n = int(0.2 * SR)
    f = sweep(2600.0, 340.0, n, 0.55)
    a = additive(f, n, "square", cutoff=sweep(9000.0, 1500.0, n), max_harm=30)
    b = additive(f * 1.012, n, "saw", cutoff=sweep(7000.0, 1200.0, n), max_harm=30)
    sub = sine(sweep(220.0, 60.0, n), n) * env_exp(n, 0.06)
    click = highpass(noise(n), 3000.0) * env_exp(n, 0.006)
    body = (a * 0.5 + b * 0.35) * env_exp(n, 0.07, 0.001)
    return fade_out(mix(body, sub * 0.6, click * 0.35), 0.02)


def sfx_hit():
    n = int(0.6 * SR)
    crunch = swept_band_noise(n, sweep(5000.0, 500.0, n, 0.6), q=1.6) * env_exp(n, 0.16, 0.001)
    bwoop = additive(sweep(950.0, 160.0, n, 0.7), n, "square", cutoff=3500.0, max_harm=25) * env_exp(n, 0.12)
    mod = sine(1730.0, n) * 3.0 * env_exp(n, 0.1)
    ring = np.sin(phase_of(1180.0, n) + mod) * env_exp(n, 0.18)
    sub = sine(sweep(140.0, 45.0, n), n) * env_exp(n, 0.12)
    sparkle_n = int(0.45 * SR)
    sparkle = np.zeros(n)
    for i, fr in enumerate([2093.0, 2637.0, 3136.0, 4186.0]):
        s0 = int((0.05 + i * 0.045) * SR)
        m = min(sparkle_n, n - s0)
        sparkle[s0:s0 + m] += sine(fr, m) * env_exp(m, 0.09) * 0.25
    out = mix(crunch * 0.9, bwoop * 0.4, ring * 0.3, sub * 0.8, sparkle)
    return fade_out(soft_clip(out, 1.3), 0.05)


