def arpeggio(notes, step, length, kind="square", cutoff=5000.0, decay=0.12, level=0.5):
    n = int(length * SR)
    out = np.zeros(int(step * (len(notes) - 1) * SR) + n + 1)
    for i, nm in enumerate(notes):
        v = additive(note(nm), n, kind, cutoff=cutoff, max_harm=30) * env_exp(n, decay, 0.003)
        place(out, v * level, i * step)
    return out


