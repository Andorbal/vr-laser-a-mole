def chord_stab(notes, dur, cutoff0=6000.0, cutoff1=800.0, level=0.3):
    n = int(dur * SR)
    out = np.zeros(n)
    cut = sweep(cutoff0, cutoff1, n, 0.5)
    for nm in notes:
        f = note(nm)
        for det in (0.995, 1.005):
            out += additive(f * det, n, "saw", cutoff=cut, max_harm=60) * level
    return out * env_adsr(n, 0.005, 0.15, 0.5, dur * 0.5)


